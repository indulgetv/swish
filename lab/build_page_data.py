"""Writes data/lab.js (window.SWISH_LAB) for the Results page's 'Model lab' section from lab/experiments.json and the
latest replay result (calibration). Run after any lab test: python3 lab/build_page_data.py"""
import json
from pathlib import Path
ROOT = Path(__file__).resolve().parent.parent
exp = json.loads((ROOT / "lab/experiments.json").read_text())
res = {}
for f in sorted((ROOT / "lab/results").glob("*.json")):
    res[f.stem] = json.loads(f.read_text())
cur = res.get("v1.6-lineups") or {}
out = {**exp, "current": {"label": cur.get("label"), "modelVersion": cur.get("modelVersion"), "nights": cur.get("nights"),
                          "calibration": cur.get("calibration"), "createdAt": cur.get("createdAt")}}
(ROOT / "data/lab.js").write_text("// Generated by lab/build_page_data.py — do not edit by hand.\nwindow.SWISH_LAB = " + json.dumps(out, separators=(",", ":")) + ";\n")
print("wrote data/lab.js", len(exp["experiments"]), "experiments")
